
print("Добро пожаловать в таблицу умножения!")

n = int(input("Введите число для таблицы: "))

print("=======================")
print(f"Таблица умножения до {n}:")

for i in range(1, n + 1):
    if i % 2 == 0:
        continue

    for j in range(1, n + 1):
        print(i * j, end=" ")
    
    print()

print("=======================")
print("Таблица успешно создана!")
